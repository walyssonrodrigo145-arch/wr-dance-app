// ─── Customer ─────────────────────────────────────────────────────────────────

/**
 * Creates a new customer on Asaas.
 * Returns the customer ID generated by Asaas.
 */
export async function createAsaasCustomer(params: {
  name: string;
  email?: string;
  phone?: string;
  cpfCnpj?: string;
}, apiKey?: string): Promise<string> {
  const res = await asaasRequest(
    "POST",
    `${ENV.asaasBaseUrl}/customers`,
    {
      name: params.name,
      email: params.email,
      phone: params.phone,
      cpfCnpj: params.cpfCnpj,
      notificationDisabled: false,
    },
    apiKey
  );

  if (!res.ok) {
    const body = await res.text();
    throw new Error(`[Asaas] Erro ao criar cliente: ${res.status} ${body}`);
  }

  const data = await res.json() as AsaasCustomer;
  return data.id;
}

